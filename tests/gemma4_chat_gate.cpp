/* gemma4_chat_gate -- Gemma 4's tokenizer and renderer graded against HF tokenizers / transformers (L338).  Model-free;
 * about a minute.
 *
 * Gemma 4 ships a SentencePiece-style BPE tokenizer.json: a Replace(' ' -> U+2581) normaliser, a Split(" ") the
 * normaliser leaves nothing to match (a run is one piece), a BPE model over characters with <0xXX> byte fallback, a
 * Replace / ByteFallback / Fuse decoder.  bpe_tokenizer runs it as its "gemma4" row (the SentencePiece-BPE pipeline:
 * one merge loop with the byte-level rows, symbols per character).  Goldens: tests/test-vectors/gemma4/, generated by
 * tests/gemma4/gen_tok_goldens.py from tokenizers' Tokenizer (meta.json records the versions and the input hashes).
 *
 *   T1 adversarial strings        encode(text) == HF ids (the shared strings, Gemma's cases, random)
 *   T2 span guard                 encode(text, client spans) == tokenizers' components with added tokens cut only
 *                                 outside the spans
 *   T3 every scalar value         per-4096-codepoint chunk: count + sha1(ids) == HF
 *   T4 calibration corpus         count + sha1(ids) == HF   (--calib)
 *   T5 token bytes                token_bytes(id) == HF decode([id]) on 3601 ids (a lone byte-fallback byte >= 0x80
 *                                 decodes to U+FFFD in HF; the engine keeps the byte, so those compare as U+FFFD)
 *   T6 the facts                  the pattern is "gemma4"; 262144 ids; stop ids = generation_config's [1, 106, 50]
 *   R1 render hand cases          gemma4_chat_render == apply_chat_template byte for byte (the template's edges: the
 *                                 system turn, thinking, reasoning placement, strip_thinking, the tools block, calls
 *                                 and results, continuations, refusals by key); the message spans == the sentinel
 *                                 render's; the guarded ids == HF's (tests/gemma4/gen_render_goldens.py)
 *   R2 render corpus              the L216 corpus in two configurations (A: thinking off, no generation prompt; B:
 *                                 thinking on for even cases, the generation prompt): per file, sha1 of the texts and
 *                                 of the guarded ids == HF's (--cases)
 *   C1 the turn-by-turn front     head + turn == the full render of the same conversation (a system message, user
 *                                 turns, thinking on and off)
 *
 * usage: gemma4_chat_gate --tok DIR --vectors DIR [--calib FILE] [--cases DIR]
 *        DIR = the checkpoint's tokenizer.json + generation_config.json */
