/* T3's context for one codepoint c (gen_tok_goldens.py sweep_text) */
static std::string sweep_context(const std::string &c) { return "x" + c + c + c + " " + c + "1'" + c + "Ab" + c + "\n"; }

/* T5: each sampled id's stored bytes against HF's decode of it alone */
static void t5_decode(const bpe_tokenizer *t, const std::string &dir) {
    const pyjson_value v = load_json(dir + "/tok_decode.json");
    int n = 0, bad = 0;
    for (const pyjson_value &e : v.a) {
        const int id = atoi(e.get("id")->num.c_str());
        const std::string &want = e.get("text")->s;
        size_t len = 0;
        const char *b = bpe_tokenizer_token_bytes(t, id, &len);
        std::string got = b ? std::string(b, len) : std::string();
        if (got.size() == 1 && (unsigned char)got[0] >= 0x80) got = "\xef\xbf\xbd";   /* HF: a lone byte -> U+FFFD */
        n++;
        if (got != want && bad++ < 5) fail("T5 id %d: bytes '%s' != HF decode '%s'", id, got.c_str(), want.c_str());
    }
    CHECK(bad == 0, "T5 %d of %d token byte strings differ from HF decode", bad, n);
    printf("T5 token bytes: %d ids, %d differ\n", n, bad);
}

/* ---- the API conversation -> renderer input ---------------------------------------------------------------- */

struct conv {
    std::vector<gemma4_msg_in> msgs;
    std::vector<std::vector<gemma4_tool_call_in>> calls;
    std::vector<std::string> store;   /* owned strings; reserved up front so c_str() stays put */
    std::string tools;
    bool has_tools = false;
    bool parts = false;               /* a content-parts message: v1's renderer takes text only */
};

static const char *keep(conv *c, const std::string &s) {
    c->store.push_back(s);
    return c->store.back().c_str();
}
static const char *keep_str(conv *c, const pyjson_value *v) {
    return v && v->kind == pyjson_value::STR ? keep(c, v->s) : NULL;
}

static void build_conv(const pyjson_value &messages, const pyjson_value *tools, conv *c) {
    size_t strings = 1;
    for (const auto &m : messages.a) {
        strings += 6;
        if (const pyjson_value *tc = m.get("tool_calls")) strings += 3 * tc->a.size();
    }
    c->store.reserve(strings);
    c->msgs.resize(messages.a.size());
    c->calls.resize(messages.a.size());
    for (size_t i = 0; i < messages.a.size(); i++) {
        const pyjson_value &m = messages.a[i];
        gemma4_msg_in &q = c->msgs[i];
        q = {};
        const pyjson_value *role = m.get("role");
        q.role = keep(c, role ? role->s : "");
        q.content = keep_str(c, m.get("content"));
        c->parts |= m.get("content") && m.get("content")->kind == pyjson_value::ARR;
        q.reasoning = keep_str(c, m.get("reasoning_content"));
        q.tool_call_id = keep_str(c, m.get("tool_call_id"));
        q.name = keep_str(c, m.get("name"));
        if (const pyjson_value *tcs = m.get("tool_calls")) {
            for (const auto &tc : tcs->a) {
                const pyjson_value *fn = tc.get("function");
                if (!fn) fn = &tc;
                const pyjson_value *args = fn->get("arguments");
                std::string a;
                if (args && args->kind == pyjson_value::STR) a = args->s;
                else if (args && args->kind != pyjson_value::NUL) pyjson_dump(*args, &a);
                c->calls[i].push_back({keep_str(c, tc.get("id")), keep_str(c, fn->get("name")), keep(c, a)});
            }
            q.calls = c->calls[i].data();
            q.n_calls = (int)c->calls[i].size();
        }
    }
    if (tools && tools->kind != pyjson_value::NUL) {
        c->has_tools = !(tools->kind == pyjson_value::ARR && tools->a.empty());
        pyjson_dump(*tools, &c->tools);
    }
}

static bool render(const conv &c, bool thinking, bool gen, gemma4_render_out *out, std::string *refusal) {
    if (c.parts) {
        *refusal = "content_parts";
        return false;
    }
    gemma4_render_in in;
    in.msgs = c.msgs.data();
    in.n_msgs = (int)c.msgs.size();
    in.tools_json = c.has_tools ? c.tools.c_str() : NULL;
    in.thinking = thinking;
    in.add_generation_prompt = gen;
    char err[400];
    if (gemma4_chat_render(in, out, err, sizeof err)) return true;
    const char *colon = strchr(err, ':');
    refusal->assign(err, colon ? (size_t)(colon - err) : strlen(err));
    return false;
}

static std::string spans_text(const std::vector<pulsar_text_span> &spans) {
    std::string s;
    char b[32];
    for (size_t i = 0; i < spans.size(); i++) {
        snprintf(b, sizeof b, "%s%u-%u", i ? "," : "", spans[i].lo, spans[i].hi);
        s += b;
    }
    return s;
}

/* the spans outside the tools block (from the first <|tool> to the last <tool|>: the generator derives the others) */
static std::vector<pulsar_text_span> message_spans(const std::string &text, const std::vector<pulsar_text_span> &spans) {
    const size_t lo = text.find("<|tool>"), hi = text.rfind("<tool|>");
    std::vector<pulsar_text_span> out;
    for (const auto &s : spans)
        if (lo == std::string::npos || hi == std::string::npos || s.hi <= lo || s.lo >= hi) out.push_back(s);
    return out;
}

static std::string hex(pulsar::Sha1 &h) {
    uint8_t d[20];
    h.final(d);
    char x[41];
    for (int i = 0; i < 20; i++) snprintf(x + 2 * i, 3, "%02x", d[i]);
    return x;
}

static void r1_hand(const bpe_tokenizer *t, const std::string &dir) {
    const pyjson_value v = load_json(dir + "/render_cases.json");
    int bad = 0, refusals = 0, guarded = 0, no_spans = 0;
    for (const auto &c : v.a) {
        const std::string &name = c.get("name")->s;
        conv cv;
        build_conv(*c.get("messages"), c.get("tools"), &cv);
        gemma4_render_out out;
        std::string refusal;
        const bool ok = render(cv, c.get("thinking")->b, c.get("gen")->b, &out, &refusal);
        const pyjson_value *ex = c.get("expect");
        const int before = g_fail;
        g_checks++;
        if (const pyjson_value *want_refusal = ex->get("refusal")) {
            refusals++;
            if (ok || refusal != want_refusal->s)
                fail("R1 %s: expected refusal %s, got %s", name.c_str(), want_refusal->s.c_str(),
                     ok ? "a render" : refusal.c_str());
        } else if (!ok) {
            fail("R1 %s: refused (%s)", name.c_str(), refusal.c_str());
        } else {
            const std::string &want = ex->get("text")->s;
            if (out.text != want) {
                size_t i = 0;
                while (i < out.text.size() && i < want.size() && out.text[i] == want[i]) i++;
                std::string ours, theirs;
                pyjson_dump_string(out.text.data() + i, std::min<size_t>(80, out.text.size() - i), &ours);
                pyjson_dump_string(want.data() + i, std::min<size_t>(80, want.size() - i), &theirs);
                fail("R1 %s: text differs at byte %zu: ours %s vs HF %s", name.c_str(), i, ours.c_str(), theirs.c_str());
            }
            const pyjson_value *sp = ex->get("spans");
            if (sp && sp->kind == pyjson_value::ARR) {
                const std::string ours = spans_text(message_spans(out.text, out.spans));
                const std::string theirs = spans_text(json_spans(*sp));
                if (ours != theirs) fail("R1 %s: spans %s vs HF %s", name.c_str(), ours.c_str(), theirs.c_str());
            } else {
                no_spans++;
            }
            const pyjson_value *ids = ex->get("ids");
            if (ids && ids->kind == pyjson_value::ARR) {
                const std::vector<int> got = encode(t, out.text, &out.spans), want_ids = json_ids(*ids);
                if (got != want_ids) fail("R1 %s: ids %s", name.c_str(), first_diff(got, want_ids).c_str());
                guarded += ex->get("ids_kind")->s == "guarded";
            }
        }
        bad += g_fail != before;
    }
    printf("R1 render hand cases: %zu (%d refusals, %d graded on the guarded ids, %d without derivable spans), "
           "%d mismatched\n", v.a.size(), refusals, guarded, no_spans, bad);
}

static void r2_corpus(const bpe_tokenizer *t, const std::string &dir, const std::string &cases_dir) {
    std::string tsv;
    if (!read_file(dir + "/render_corpus.tsv", &tsv)) { fail("R2: no render_corpus.tsv"); return; }
    int lines = 0, bad = 0, cases_total = 0, rendered_total = 0, compared_total = 0;
    long tokens_total = 0;
    std::map<std::string, int> refusals_total;
    std::string cur_file;
    pyjson_value cases;
    for (size_t pos = 0; pos < tsv.size();) {
        const size_t nl = tsv.find('\n', pos);
        const std::string line = tsv.substr(pos, nl - pos);
        pos = nl + 1;
        if (line.empty() || line[0] == '#') continue;
        std::vector<std::string> f;
        for (size_t a = 0;;) {
            const size_t b = line.find('\t', a);
            f.push_back(line.substr(a, b - a));
            if (b == std::string::npos) break;
            a = b + 1;
        }
        if (f.size() != 10) { fail("R2: bad golden line"); continue; }
        if (f[0] != cur_file) {
            cases = load_json(cases_dir + "/" + f[0]);
            cur_file = f[0];
        }
        const bool cfg_b = f[1] == "B";
        std::vector<size_t> nodiv;
        for (size_t a = 0; f[9] != "-" && a < f[9].size();) {
            const size_t b = f[9].find(',', a);
            nodiv.push_back((size_t)atol(f[9].substr(a, b - a).c_str()));
            if (b == std::string::npos) break;
            a = b + 1;
        }
        pulsar::Sha1 ht, hi;
        int ok = 0, ncmp = 0;
        long ntok = 0;
        std::map<std::string, int> refused;
        for (size_t idx = 0; idx < cases.a.size(); idx++) {
            const pyjson_value &c = cases.a[idx];
            conv cv;
            build_conv(*c.get("messages"), c.get("tools"), &cv);
            gemma4_render_out out;
            std::string refusal;
            if (!render(cv, cfg_b && idx % 2 == 0, cfg_b, &out, &refusal)) {
                refused[refusal]++;
                const std::string l = std::to_string(idx) + " refuse " + refusal + "\n";
                ht.update(l.data(), l.size());
                continue;
            }
            ok++;
            const std::string l = std::to_string(idx) + " " + sha1_hex(out.text) + "\n";
            ht.update(l.data(), l.size());
            if (std::find(nodiv.begin(), nodiv.end(), idx) != nodiv.end()) continue;
            const std::vector<int> ids = encode(t, out.text, &out.spans);
            ncmp++;
            ntok += (long)ids.size();
            const std::string li = std::to_string(idx) + " " + sha1_hex(ids_text(ids)) + "\n";
            hi.update(li.data(), li.size());
        }
        const std::string h1 = hex(ht), h2 = hex(hi);
        std::string ref;
        for (const auto &kv : refused) ref += (ref.empty() ? "" : ",") + kv.first + "=" + std::to_string(kv.second);
        if (ref.empty()) ref = "-";
        lines++;
        cases_total += (int)cases.a.size();
        rendered_total += ok;
        compared_total += ncmp;
        tokens_total += ntok;
        for (const auto &kv : refused) refusals_total[kv.first] += kv.second;
        g_checks++;
        if (std::to_string(ok) != f[3] || ref != f[4] || h1 != f[5] || h2 != f[6] || std::to_string(ntok) != f[7] ||
            std::to_string(ncmp) != f[8]) {
            bad++;
            fail("R2 %s cfg %s: rendered %d/%s refusals %s/%s text %s ids %s tokens %ld/%s compared %d/%s", f[0].c_str(),
                 f[1].c_str(), ok, f[3].c_str(), ref.c_str(), f[4].c_str(), h1 == f[5] ? "=" : "DIFF",
                 h2 == f[6] ? "=" : "DIFF", ntok, f[7].c_str(), ncmp, f[8].c_str());
        }
    }
    std::string ref;
    for (const auto &kv : refusals_total) ref += " " + kv.first + "=" + std::to_string(kv.second);
    printf("R2 render corpus: %d file x config lines, %d cases, %d rendered (%d with ids graded, %ld tokens), "
           "refusals:%s; %d mismatched\n", lines, cases_total, rendered_total, compared_total, tokens_total,
           ref.empty() ? " none" : ref.c_str(), bad);
}

/* C1: the turn-by-turn front (head, then turns, each closed as a sampled turn is) == the full render */
static void c1_composition(void) {
    int bad = 0, n = 0;
    for (int think = 0; think < 2; think++)
        for (const char *sys : {(const char *)NULL, "  Be brief.  "}) {
            gemma4_msg_in m[5] = {};
            int k = 0;
            if (sys) m[k++] = {"system", sys, NULL, NULL, 0, NULL, NULL};
            m[k++] = {"user", " first question ", NULL, NULL, 0, NULL, NULL};
            m[k++] = {"assistant", "first answer", NULL, NULL, 0, NULL, NULL};
            m[k++] = {"user", "second", NULL, NULL, 0, NULL, NULL};
            gemma4_render_in in = {m, k, NULL, (bool)think, true};
            gemma4_render_out full, head, t1, t2;
            char err[300];
            const int s = sys ? 1 : 0;
            bool ok = gemma4_chat_render(in, &full, err, sizeof err) &&
                      gemma4_chat_render_head(sys, think, &head, err, sizeof err) &&
                      gemma4_chat_render_turn(m + s, 1, think, false, &t1, err, sizeof err) &&
                      gemma4_chat_render_turn(m + s + 1, 2, think, true, &t2, err, sizeof err);
            /* the full render's assistant turn is "<|turn>model\nfirst answer<turn|>\n": the head + the user turn +
             * that turn + the second turn compose it */
            const std::string composed = head.text + t1.text + t2.text;
            n++;
            g_checks++;
            if (!ok || composed != full.text) {
                bad++;
                fail("C1 think %d system %s: head + turns != the full render (%s)", think, sys ? "yes" : "no",
                     ok ? "text differs" : err);
            }
        }
    printf("C1 turn-by-turn composition: %d conversations, %d mismatched\n", n, bad);
}

int main(int argc, char **argv) {
    std::string tok_dir, vec_dir, calib, cases;
    for (int i = 1; i < argc; i++) {
        const std::string a = argv[i];
        if (a == "--tok" && i + 1 < argc) tok_dir = argv[++i];
        else if (a == "--vectors" && i + 1 < argc) vec_dir = argv[++i];
        else if (a == "--calib" && i + 1 < argc) calib = argv[++i];
        else if (a == "--cases" && i + 1 < argc) cases = argv[++i];
        else {
            fprintf(stderr, "usage: gemma4_chat_gate --tok DIR --vectors DIR [--calib FILE] [--cases DIR]\n");
            return 2;
        }
    }
    if (tok_dir.empty() || vec_dir.empty()) {
        fprintf(stderr, "usage: gemma4_chat_gate --tok DIR --vectors DIR [--calib FILE]\n");
        return 2;
    }
    std::string tj, gj;
    if (!read_file(tok_dir + "/tokenizer.json", &tj) || !read_file(tok_dir + "/generation_config.json", &gj)) {
        fprintf(stderr, "gemma4_chat_gate: %s must hold tokenizer.json and generation_config.json\n", tok_dir.c_str());
        return 2;
    }
    char err[300];
    bpe_tokenizer *t = bpe_tokenizer_load_hf(tj.data(), tj.size(), gj.data(), gj.size(), err, sizeof err);
    if (!t) {
        fprintf(stderr, "gemma4_chat_gate: the tokenizer refused: %s\n", err);
        return 1;
    }
    const std::vector<int> &stop = bpe_tokenizer_stop_ids(t);
    CHECK(!strcmp(bpe_tokenizer_pattern(t)->name, "gemma4"), "T6 pattern %s", bpe_tokenizer_pattern(t)->name);
    CHECK(bpe_tokenizer_n_tokens(t) == 262144, "T6 %d ids", bpe_tokenizer_n_tokens(t));
    CHECK(stop.size() == 3 && stop[0] == 1 && stop[1] == 106 && stop[2] == 50, "T6 stop ids are not [1, 106, 50]");
    printf("tokenizer: %s (gemma4: SentencePiece-BPE, byte fallback), %d ids, stops %d %d %d\n", tok_dir.c_str(),
           bpe_tokenizer_n_tokens(t), stop.size() > 0 ? stop[0] : -1, stop.size() > 1 ? stop[1] : -1,
           stop.size() > 2 ? stop[2] : -1);
    t1_adversarial(t, vec_dir);
    t2_spans(t, vec_dir);
    t3_sweep(t, vec_dir, sweep_context);
    if (!calib.empty()) t4_calib(t, vec_dir, calib);
    t5_decode(t, vec_dir);
    r1_hand(t, vec_dir);
    if (!cases.empty()) r2_corpus(t, vec_dir, cases);
    c1_composition();
    bpe_tokenizer_free(t);
    printf("\ngemma4_chat_gate: %d checks, %s\n", g_checks, g_fail ? "FAIL" : "PASS");
    return g_fail ? 1 : 0;
}
