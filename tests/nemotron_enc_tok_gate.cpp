/* nemotron_enc_tok_gate -- the Nemotron-3.5 encoders' tokenizer graded against HF tokenizers (L321).  Model-free;
 * seconds.
 *
 * The encoders (Embed-8B / Rerank-8B) ship tekken with a normaliser the Nemotron-H row does not have: a Replace pair
 * that drops a zero-width non-joiner (U+200C) after '[' or '<' (their chat template writes one into client text so
 * no added token can form there).  bpe_tokenizer's "tekken" pattern carries two rows; the file's normaliser picks
 * this one, and the run normaliser drops the ZWNJs before the split.  Goldens: tests/test-vectors/nemotron_enc/,
 * generated by tests/nemotron_enc/gen_tok_goldens.py from tokenizers' Tokenizer (meta.json records the versions and
 * the input hashes).
 *
 *   T1 adversarial strings        encode(text) == HF ids (the Nemotron-H gate's strings, the ZWNJ cases, random)
 *   T2 span guard                 encode(text, client spans) == tokenizers' components with added tokens cut only
 *                                 outside the spans (the normaliser per run)
 *   T3 every scalar value         per-4096-codepoint chunk: count + sha1(ids) == HF
 *   T4 calibration corpus         count + sha1(ids) == HF   (--calib)
 *
 * The checkpoints carry no generation_config.json; the eos config the loader takes is the one fact the family
 * reads too: config.json text_config.eos_token_id.
 *
 * usage: nemotron_enc_tok_gate --tok DIR --vectors DIR [--calib FILE]
 *        DIR = the checkpoint's tokenizer.json + config.json */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include <string>
#include <vector>

#include "bpe_gate_util.h"

/* T3's context for one codepoint c (gen_tok_goldens.py sweep_text) */
static std::string sweep_context(const std::string &c) { return "x" + c + c + c + " " + c + "1'" + c + "Ab" + c + "\n"; }

int main(int argc, char **argv) {
    std::string tok_dir, vec_dir, calib;
    for (int i = 1; i < argc; i++) {
        const std::string a = argv[i];
        if (a == "--tok" && i + 1 < argc) tok_dir = argv[++i];
        else if (a == "--vectors" && i + 1 < argc) vec_dir = argv[++i];
        else if (a == "--calib" && i + 1 < argc) calib = argv[++i];
        else {
            fprintf(stderr, "usage: nemotron_enc_tok_gate --tok DIR --vectors DIR [--calib FILE]\n");
            return 2;
        }
    }
    if (tok_dir.empty() || vec_dir.empty()) {
        fprintf(stderr, "usage: nemotron_enc_tok_gate --tok DIR --vectors DIR [--calib FILE]\n");
        return 2;
    }
    std::string tj, cj;
    if (!read_file(tok_dir + "/tokenizer.json", &tj) || !read_file(tok_dir + "/config.json", &cj)) {
        fprintf(stderr, "nemotron_enc_tok_gate: %s must hold tokenizer.json and config.json\n", tok_dir.c_str());
        return 2;
    }
    pyjson_value cfg;
    char err[300];
    const pyjson_value *eos = NULL;
    if (pyjson_parse(cj.data(), cj.size(), &cfg, err, sizeof err) && cfg.get("text_config"))
        eos = cfg.get("text_config")->get("eos_token_id");
    if (!eos || eos->kind != pyjson_value::INT) {
        fprintf(stderr, "nemotron_enc_tok_gate: config.json has no text_config.eos_token_id\n");
        return 2;
    }
    const std::string eos_cfg = "{\"eos_token_id\": " + eos->num + "}";
    bpe_tokenizer *t = bpe_tokenizer_load_hf(tj.data(), tj.size(), eos_cfg.data(), eos_cfg.size(), err, sizeof err);
    if (!t) {
        fprintf(stderr, "nemotron_enc_tok_gate: the tokenizer refused: %s\n", err);
        return 1;
    }
    printf("tokenizer: %s (tekken + the U+200C Replace pair), eos %s\n", tok_dir.c_str(), eos->num.c_str());
    t1_adversarial(t, vec_dir);
    t2_spans(t, vec_dir);
    t3_sweep(t, vec_dir, sweep_context);
    if (!calib.empty()) t4_calib(t, vec_dir, calib);
    bpe_tokenizer_free(t);
    printf("\nnemotron_enc_tok_gate: %d checks, %s\n", g_checks, g_fail ? "FAIL" : "PASS");
    return g_fail ? 1 : 0;
}
