#!/usr/bin/env python3
"""gen_py_unprintable.py -- src/lib/py_unprintable.inc: the code points CPython's repr() escapes (str.isprintable() is False).

    python3 tools/gen_py_unprintable.py > src/lib/py_unprintable.inc

The table follows the Unicode version of the Python that runs this, named in the file."""
import sys
import unicodedata

ranges, start = [], None
for cp in range(0x110000):
    if not chr(cp).isprintable():
        if start is None:
            start = cp
    elif start is not None:
        ranges.append((start, cp - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10ffff))
print(f"/* Generated by tools/gen_py_unprintable.py (Python {sys.version_info[0]}.{sys.version_info[1]}, "
      f"Unicode {unicodedata.unidata_version}): do not edit. */")
for a, b in ranges:
    print(f"{{0x{a:x}, 0x{b:x}}},")
