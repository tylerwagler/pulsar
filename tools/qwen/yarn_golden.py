#!/usr/bin/env python3
"""L280: the golden tables tests/qsa_yarn_test grades pulsar_qsa_rope_init against -- transformers' own rope init for
Qwen3.8-Flash-Next, evaluated by transformers.

  yarn_golden.py --config CONFIG.json [--factor 4.0] > tests/qsa_yarn_golden.h

CONFIG.json is the Hugging Face snapshot's config.json (its text_config is the model's; the snapshot ships
`rope_type: default`).  The YaRN rope is the model card's recipe: that rope_parameters with rope_type yarn, factor 4.0,
original_max_position_embeddings 262144 (transformers' default beta_fast 32 / beta_slow 1, truncate true).

For the native rope and for YaRN the header carries
  - transformers' f32 table: the function as shipped (pos_freqs, the ramp and the blend in torch float32), and
  - transformers' f64 table rounded once to f32: the SAME function with torch's float32 dtypes mapped to float64 while
    it runs -- the exact value of each frequency, which is what the engine computes (double, one rounding),
plus the attention factor (Python double, as transformers returns it).  The test asserts the engine's table equals
the f64 one bit for bit, and reports its ulp distance from the f32 one (torch's f32 pow / division / blend round
several times).
"""
import argparse
import copy
import json
import struct

import torch
from transformers.models.qwen4_exp.configuration_qwen4_exp import Qwen4ExpTextConfig
from transformers import modeling_rope_utils as mru


def f32_bits(x):
    return struct.unpack("<I", struct.pack("<f", float(x)))[0]


def table(cfg, f64):
    """transformers' rope init for cfg; in float64 when f64 (torch.float / torch.float32 mapped to float64)."""
    rope_type = cfg.rope_parameters["rope_type"]
    if rope_type == "default":
        # Qwen4ExpTextRotaryEmbedding.compute_default_rope_parameters
        from transformers.models.qwen4_exp.modeling_qwen4_exp import Qwen4ExpTextRotaryEmbedding as R
        fn = R.compute_default_rope_parameters
    else:
        fn = mru.ROPE_INIT_FUNCTIONS[rope_type]
    if not f64:
        inv, att = fn(cfg)
        return inv.to(torch.float32), att
    saved = (torch.float, torch.float32)
    try:
        torch.float = torch.float64
        torch.float32 = torch.float64
        inv, att = fn(cfg)
    finally:
        torch.float, torch.float32 = saved
    assert inv.dtype == torch.float64, inv.dtype
    return inv, att


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--factor", type=float, default=4.0)
    a = ap.parse_args()
    text = json.load(open(a.config))["text_config"]
    native = Qwen4ExpTextConfig(**text)
    yt = copy.deepcopy(text)
    yt["rope_parameters"] = dict(text["rope_parameters"], rope_type="yarn", factor=a.factor,
                                 original_max_position_embeddings=text["max_position_embeddings"])
    yarn = Qwen4ExpTextConfig(**yt)
    out = []
    out.append("/* GENERATED by tools/qwen/yarn_golden.py (L280) from the Qwen3.8-Flash-Next config -- do not edit.")
    out.append(" * transformers %s, torch %s.  f32 bits of each rotary pair's inverse frequency. */" % (
        __import__("transformers").__version__, torch.__version__))
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    for name, cfg in (("native", native), ("yarn", yarn)):
        t32, att32 = table(cfg, False)
        t64, att64 = table(cfg, True)
        assert att32 == att64, (att32, att64)
        n = t32.numel()
        out.append("static const uint32_t qsa_golden_%s_hf_f32[%d] = {%s};" % (
            name, n, ", ".join("0x%08xu" % f32_bits(v) for v in t32.tolist())))
        out.append("static const uint32_t qsa_golden_%s_f64[%d] = {%s};" % (
            name, n, ", ".join("0x%08xu" % f32_bits(v) for v in t64.tolist())))
        out.append("static const double qsa_golden_%s_attention_factor = %r;" % (name, float(att32)))
    rp = yarn.rope_parameters
    out.append("static const double qsa_golden_yarn_factor = %r;" % float(rp["factor"]))
    out.append("static const uint32_t qsa_golden_yarn_orig_ctx = %du;" % int(rp["original_max_position_embeddings"]))
    print("\n".join(out))


if __name__ == "__main__":
    main()
